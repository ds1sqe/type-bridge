macro_rules! canonical_text {
    ($value:expr) => {{
        String::from_utf8(to_canonical_json($value)?).map_err(|_| {
            invalid(
                "rust_emitter_non_utf8_canonical_json",
                "canonical JSON must be UTF-8",
            )
        })?
    }};
}

