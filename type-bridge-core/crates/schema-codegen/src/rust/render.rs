    output.push_str("];\n\npub const MODEL_LINK_COMPONENTS: &[&[&str]] = &[\n");
    for component in projection.emission().model_link_components() {
        output.push_str("  &[");
        for id in component {
            let _ = write!(output, "{},", rust_literal(&canonical_text!(id)));
        }
        output.push_str("],\n");
    }
    output.push_str("];\n\npub const STRUCT_ORDER: &[&str] = &[\n");
    for id in projection.emission().structs() {
        let _ = writeln!(output, "  {},", rust_literal(&canonical_text!(id)));
    }
    output.push_str("];\n\npub const FUNCTION_ORDER: &[&str] = &[\n");
    for id in projection.emission().functions() {
        let _ = writeln!(output, "  {},", rust_literal(&canonical_text!(id)));
    }
