fn create_auxiliary_type_symbols(
    projection: &RuntimeProjection,
    model: &ModelProjection,
    prefix: &str,
) -> Result<Vec<String>, Diagnostic> {
    let Some(args) = create_args_type(model)? else {
        return Ok(Vec::new());
    };
    let mut symbols = vec![args];
    for field in model.create().fields() {
        if field.multiplicity().container() == ProjectedContainer::Sequence {
            let member = entity_field_parameter(model, prefix, field.token())?;
            projected_attribute_model(projection, field.value())?;
            symbols.push(create_member_sequence_type(model, &member)?);
        }
    }
    for role in model.create().roles().values() {
        if role.multiplicity().container() == ProjectedContainer::Sequence {
            let member = relation_role_parameter(model, prefix, role.role())?;
            relation_role_union(model, role.role())?;
            symbols.push(create_member_sequence_type(model, &member)?);
        }
    }
    Ok(symbols)
}

fn entity_reference_symbols(
    model: &ModelProjection,
    prefix: &str,
) -> Result<Vec<String>, Diagnostic> {
    let Some(target) = model.reference_read().target_name() else {
        return Ok(Vec::new());
    };
    let mut symbols = vec![
        generated_symbol(target.as_str(), "from_iid")?,
        generated_symbol(target.as_str(), "iid")?,
        generated_symbol(target.as_str(), "close")?,
    ];
    for field in model.reference_read().key_fields() {
        let projected = model.query_tokens().fields().get(field).ok_or_else(|| {
            invalid(
                "c_emitter_reference_key_missing",
                "projected C reference key is absent from query fields",
            )
        })?;
        let constructor_suffix = if model.reference_read().key_fields().len() == 1 {
            "from_key".to_owned()
        } else {
            format!(
                "from_{}",
                projected_member_suffix(prefix, projected.target_name())?
            )
        };
        symbols.push(generated_symbol(target.as_str(), &constructor_suffix)?);
    }
    for field in model.reference_read().key_fields() {
        let projected = model.query_tokens().fields().get(field).ok_or_else(|| {
            invalid(
                "c_emitter_reference_key_missing",
                "projected C reference key is absent from query fields",
            )
        })?;
        symbols.push(generated_symbol(
            target.as_str(),
            &format!(
                "{}_key",
                projected_member_suffix(prefix, projected.target_name())?
            ),
        )?);
    }
    Ok(symbols)
}

fn entity_complete_symbols(
    model: &ModelProjection,
    prefix: &str,
) -> Result<Vec<String>, Diagnostic> {
    let target = model.target_name().as_str();
    let mut symbols = vec![
        generated_symbol(target, "iid")?,
        generated_symbol(target, "reference")?,
        generated_symbol(target, "close")?,
    ];
    for field in model.complete_read().fields() {
        let projected = model
            .query_tokens()
            .fields()
            .get(field.token())
            .ok_or_else(|| {
                invalid(
                    "c_emitter_complete_field_missing",
                    "projected C complete field is absent from query fields",
                )
            })?;
        let member = projected_member_suffix(prefix, projected.target_name())?;
        match field.multiplicity().container() {
            ProjectedContainer::Scalar => {
                symbols.push(generated_symbol(target, member)?);
            }
            ProjectedContainer::Sequence => {
                symbols.push(generated_symbol(target, &format!("{member}_count"))?);
                symbols.push(generated_symbol(target, &format!("{member}_at"))?);
            }
        }
    }
    for role in model.complete_read().roles().values() {
        let projected = model
            .query_tokens()
            .roles()
            .get(role.role())
            .ok_or_else(|| {
                invalid(
                    "c_emitter_complete_role_missing",
                    "projected C complete role is absent from query role tokens",
                )
            })?;
        let member = projected_member_suffix(prefix, projected.target_name())?;
        match role.multiplicity().container() {
            ProjectedContainer::Scalar => {
                symbols.push(generated_symbol(target, member)?);
            }
            ProjectedContainer::Sequence => {
                symbols.push(generated_symbol(target, &format!("{member}_count"))?);
                symbols.push(generated_symbol(target, &format!("{member}_at"))?);
            }
        }
    }
    Ok(symbols)
}

