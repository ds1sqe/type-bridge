const TEMPLATE_PREFIX: &str = "@TYPE_BRIDGE_C_SYMBOL_PREFIX@";
const C_MAX_TARGET_IDENTIFIER_BYTES: usize = 255;
const C_TRANSLATION_UNIT_IDENTIFIER_MAX: usize = 4_095;
const C_SIMULTANEOUS_MACRO_MAX: usize = 4_095;
const C_HOSTED_OBJECT_BYTES_MIN: usize = 65_535;
const C_EMBEDDED_BYTE_CHUNK_MAX: usize = 32_768;
const C_CREATE_ARGS_VERSION: u32 = 1;
const C_RUNTIME_HEADER_EXTERNAL_IDENTIFIER_COUNT: usize = 340;
const C_RUNTIME_HEADER_MACRO_IDENTIFIER_COUNT: usize = 262;
// GCC, Clang, MinGW GCC, and clang-cl require at most 715 predefined or
// stddef/stdint platform macros beyond the repository-owned runtime header.
// Keep a power-of-two reserve above that measured maximum so compiler updates
// cannot consume the complete C minimum without tripping the parity test.
const C_SUPPORTED_IMPLEMENTATION_MACRO_RESERVE: usize = 1_024;
const C_GENERATED_SYMBOL_DOMAIN: &str = "typebridge.generator.c-symbol";
const C_GENERATED_SYMBOL_CANONICALIZATION: &str = "typebridge.c-generated-symbol/v2";

pub(super) fn render(
    projection: &RuntimeProjection,
    authority: &EmbeddedAuthority,
    cmake_template: &[u8],
    cmake_package_config_template: &[u8],
    pkg_config_template: &[u8],
) -> Result<GeneratedPackage, Diagnostic> {
    let ordered = projection_uses_ordered_collections(projection);
    let prefix = projection
        .config()
        .c_symbol_prefix()
        .ok_or_else(|| {
            invalid(
                "c_emitter_missing_symbol_prefix",
                "C projection has no symbol prefix",
            )
        })?
        .as_str();
    let header_path = format!("include/{prefix}/models.h");
    let pkg_config_path = format!("{prefix}.pc.in");
    let cmake_package_config_path = format!("{prefix}Config.cmake.in");
    let cmake = render_template(cmake_template, prefix, "c_emitter_invalid_cmake_template")?;
    let cmake_package_config = render_template(
        cmake_package_config_template,
        prefix,
        "c_emitter_invalid_cmake_package_config_template",
    )?;
    let pkg_config = render_template(
        pkg_config_template,
        prefix,
        "c_emitter_invalid_pkg_config_template",
    )?;
    let projection_json = to_canonical_json(projection)?;
    let semantic_json = to_canonical_json(projection.semantic_fingerprint())?;
    let binding_json = to_canonical_json(projection.projection_fingerprint())?;

    validate_c_projection_limits(projection, prefix, ordered)?;

    GeneratedPackage::try_new([
        ("CMakeLists.txt".to_owned(), cmake.into_bytes()),
        (cmake_package_config_path, cmake_package_config.into_bytes()),
        (
            header_path,
            render_header(projection, prefix, ordered)?.into_bytes(),
        ),
        (
            "src/models.c".to_owned(),
            render_source(
                projection,
                prefix,
                authority,
                &projection_json,
                &semantic_json,
                &binding_json,
                ordered,
            )?
            .into_bytes(),
        ),
        (pkg_config_path, pkg_config.into_bytes()),
    ])
}

fn render_template(bytes: &[u8], prefix: &str, code: &'static str) -> Result<String, Diagnostic> {
    let template = std::str::from_utf8(bytes)
        .map_err(|_| invalid(code, "fixed C package template must be UTF-8"))?;
    if !template.contains(TEMPLATE_PREFIX) {
        return Err(invalid(
            code,
            "fixed C package template is missing its symbol-prefix placeholder",
        ));
    }
    Ok(template.replace(TEMPLATE_PREFIX, prefix))
}

fn render_header(
    projection: &RuntimeProjection,
    prefix: &str,
    ordered: bool,
) -> Result<String, Diagnostic> {
    validate_generated_symbols(projection, prefix, ordered)?;
    let guard = format!("{}_TYPE_BRIDGE_MODELS_H", prefix.to_ascii_uppercase());
    let macro_prefix = prefix.to_ascii_uppercase();
    let mut output = format!(
        "/* Generated by type-bridge from a verified C RuntimeProjection. Do not edit. */\n\
         #ifndef {guard}\n#define {guard}\n\n\
         #include <typebridge/type_bridge.h>\n\n\
         #define {macro_prefix}_CREATE_ARGS_VERSION {C_CREATE_ARGS_VERSION}u\n\
         #define {macro_prefix}_CREATE_FIELD_MAX {TYPE_BRIDGE_C_CREATE_FIELD_MAX}u\n\
         #define {macro_prefix}_CREATE_ROLE_MAX {TYPE_BRIDGE_C_CREATE_ROLE_MAX}u\n\
         #define {macro_prefix}_CREATE_MEMBER_MAX {TYPE_BRIDGE_C_CREATE_MEMBER_MAX}u\n\
         #define {macro_prefix}_TRANSLATION_UNIT_IDENTIFIER_MAX {C_TRANSLATION_UNIT_IDENTIFIER_MAX}u\n\
         #define {macro_prefix}_SIMULTANEOUS_MACRO_MAX {C_SIMULTANEOUS_MACRO_MAX}u\n\
         #define {macro_prefix}_IMPLEMENTATION_MACRO_RESERVE {C_SUPPORTED_IMPLEMENTATION_MACRO_RESERVE}u\n\
         #define {macro_prefix}_HOSTED_OBJECT_BYTES_MIN {C_HOSTED_OBJECT_BYTES_MIN}u\n\n\
         #define {macro_prefix}_EMBEDDED_BYTE_CHUNK_MAX {C_EMBEDDED_BYTE_CHUNK_MAX}u\n\
         #define {macro_prefix}_SEQUENCE_OBJECT_BYTES_MAX {C_HOSTED_OBJECT_BYTES_MIN}u\n\n\
         #if defined(__cplusplus)\n\
         static_assert(TYPE_BRIDGE_PROJECTED_CREATE_BUILDER_CHUNK_LEN_MAX <=\n\
             {macro_prefix}_HOSTED_OBJECT_BYTES_MIN /\n\
                 sizeof(const type_bridge_projected_value_t *),\n\
             \"generated value scratch exceeds the C hosted-object minimum\");\n\
         static_assert(TYPE_BRIDGE_PROJECTED_CREATE_BUILDER_CHUNK_LEN_MAX <=\n\
             {macro_prefix}_HOSTED_OBJECT_BYTES_MIN /\n\
                 sizeof(const type_bridge_projected_reference_t *),\n\
             \"generated reference scratch exceeds the C hosted-object minimum\");\n\
         #else\n\
         _Static_assert(TYPE_BRIDGE_PROJECTED_CREATE_BUILDER_CHUNK_LEN_MAX <=\n\
             {macro_prefix}_HOSTED_OBJECT_BYTES_MIN /\n\
                 sizeof(const type_bridge_projected_value_t *),\n\
             \"generated value scratch exceeds the C hosted-object minimum\");\n\
         _Static_assert(TYPE_BRIDGE_PROJECTED_CREATE_BUILDER_CHUNK_LEN_MAX <=\n\
             {macro_prefix}_HOSTED_OBJECT_BYTES_MIN /\n\
                 sizeof(const type_bridge_projected_reference_t *),\n\
             \"generated reference scratch exceeds the C hosted-object minimum\");\n\
         #endif\n\n\
         #ifdef __cplusplus\nextern \"C\" {{\n#endif\n\n"
    );

    for name in projected_nominal_names(projection, ordered)? {
        let _ = writeln!(output, "typedef struct {name} {name};");
    }
    render_projected_token_declarations(&mut output, projection, prefix, ordered);
    render_attribute_declarations(&mut output, projection, prefix)?;
    render_role_union_declarations(&mut output, projection, prefix)?;
    render_entity_model_declarations(&mut output, projection, prefix)?;
    render_relation_model_declarations(&mut output, projection, prefix)?;
    if ordered {
        render_canonical_codec_declarations(&mut output, projection)?;
    }
    render_generated_helpers(&mut output, prefix)?;
    if ordered {
        render_successor_model_api(&mut output, projection, prefix)?;
    }
    query::render_inline(&mut output, projection, prefix, ordered)?;
    if ordered {
        let _ = write!(
            output,
            "\n#define {macro_prefix}_MIGRATION_HISTORY_RESOURCE \"typebridge/migration-history.json\"\n\n\
             type_bridge_status_t TYPE_BRIDGE_CALL {prefix}_schema_package_open(\n\
               type_bridge_schema_package_t **out_package,\n\
               type_bridge_diagnostics_t **out_diagnostics);\n\
             type_bridge_status_t TYPE_BRIDGE_CALL {prefix}_schema_package_open_v2(\n\
               type_bridge_schema_package_t **out_package,\n\
               type_bridge_execution_diagnostics_t **out_diagnostics);\n\n\
             type_bridge_status_t TYPE_BRIDGE_CALL {prefix}_migration_catalog_open(\n\
               type_bridge_byte_view_t history_bundle,\n\
               type_bridge_migration_catalog_t **out_catalog,\n\
               type_bridge_diagnostics_t **out_diagnostics);\n\n\
             #ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */\n"
        );
    } else {
        let _ = write!(
            output,
            "\ntype_bridge_status_t TYPE_BRIDGE_CALL {prefix}_schema_package_open(\n\
               type_bridge_schema_package_t **out_package,\n\
               type_bridge_diagnostics_t **out_diagnostics);\n\n\
             #ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */\n"
        );
    }
    Ok(output)
}

fn projected_nominal_names(
    projection: &RuntimeProjection,
    ordered: bool,
) -> Result<BTreeSet<String>, Diagnostic> {
    let mut names = BTreeSet::new();
    let mut insert = |name: &str| {
        if !names.insert(name.to_owned()) {
            return Err(invalid(
                "c_emitter_duplicate_nominal_identifier",
                "C projection repeats one nominal identifier",
            ));
        }
        Ok(())
    };

    for model in projection.models().values() {
        insert(model.target_name().as_str())?;
        if let Some(name) = model.create().target_name() {
            insert(name.as_str())?;
        }
        if let Some(name) = model.reference_read().target_name() {
            insert(name.as_str())?;
        }
        if let Some(name) = model.query_tokens().target_name() {
            insert(name.as_str())?;
        }
        for role in model.query_tokens().roles().values() {
            if let Some(name) = role.player_union_target_name() {
                insert(name.as_str())?;
            }
        }
    }
    for structure in projection.structs().values() {
        insert(structure.target_name().as_str())?;
    }
    for function in projection.functions().values() {
        insert(function.target_name().as_str())?;
    }
    for playing in projection.playing_facts().values() {
        if let Some(name) = playing.target_name() {
            insert(name.as_str())?;
        }
    }
    let prefix = projection
        .config()
        .c_symbol_prefix()
        .expect("C renderer validated its symbol prefix")
        .as_str();
    for name in query::nominal_names(projection, prefix, ordered)? {
        insert(&name)?;
    }
    if ordered {
        for model in projection.models().values() {
            for operation in successor_batch_operations(model) {
                for name in successor_batch_type_names(model, operation)? {
                    insert(&name)?;
                }
            }
        }
    }
    Ok(names)
}

fn render_source(
    projection: &RuntimeProjection,
    prefix: &str,
    authority: &EmbeddedAuthority,
    projection_json: &[u8],
    semantic_json: &[u8],
    binding_json: &[u8],
    ordered: bool,
) -> Result<String, Diagnostic> {
    validate_embedded_resource_symbols(
        projection,
        prefix,
        ordered,
        &[
            (
                "schema_authority_json",
                authority.canonical_envelope_json.len(),
            ),
            ("declared_schema_json", authority.declared_schema_json.len()),
            ("runtime_projection_json", projection_json.len()),
            ("semantic_fingerprint_json", semantic_json.len()),
            ("binding_fingerprint_json", binding_json.len()),
            ("managed_scope", authority.managed_scope_id.len()),
            ("semantic_profile", authority.semantic_profile_id.len()),
        ],
    )?;
    let mut output = format!(
        "/* Generated by type-bridge from verified canonical evidence. Do not edit. */\n\
         #include <{prefix}/models.h>\n\n"
    );
    render_projected_token_definitions(&mut output, projection, prefix, ordered);
    render_attribute_definitions(&mut output, projection, prefix)?;
    render_role_union_definitions(&mut output, projection, prefix)?;
    render_entity_model_definitions(&mut output, projection, prefix)?;
    render_relation_model_definitions(&mut output, projection, prefix)?;
    if ordered {
        render_canonical_codec_definitions(&mut output, projection, prefix)?;
    }
    render_chunked_byte_view(
        &mut output,
        &format!("{prefix}_schema_authority_json"),
        authority.canonical_envelope_json.as_bytes(),
    );
    render_chunked_byte_view(
        &mut output,
        &format!("{prefix}_declared_schema_json"),
        authority.declared_schema_json.as_bytes(),
    );
    render_chunked_byte_view(
        &mut output,
        &format!("{prefix}_runtime_projection_json"),
        projection_json,
    );
    render_chunked_byte_view(
        &mut output,
        &format!("{prefix}_semantic_fingerprint_json"),
        semantic_json,
    );
    render_chunked_byte_view(
        &mut output,
        &format!("{prefix}_binding_fingerprint_json"),
        binding_json,
    );
    render_chunked_byte_view(
        &mut output,
        &format!("{prefix}_managed_scope"),
        authority.managed_scope_id.as_bytes(),
    );
    render_chunked_byte_view(
        &mut output,
        &format!("{prefix}_semantic_profile"),
        authority.semantic_profile_id.as_bytes(),
    );

    let descriptor_abi_minor = type_bridge_contract::projection::TYPE_BRIDGE_C_ABI_MINOR;

    let _ = write!(
        output,
        "static const type_bridge_schema_package_chunked_descriptor_v1_t\n\
         {prefix}_schema_package_chunks_v1 = {{\n\
         \x20 sizeof(type_bridge_schema_package_chunked_descriptor_v1_t),\n\
         \x20 {TYPE_BRIDGE_C_ABI_MAJOR}u,\n\
         \x20 {descriptor_abi_minor}u,\n\
         \x20 0u,\n\
         \x20 {schema_authority},\n\
         \x20 {declared_schema},\n\
         \x20 {runtime_projection},\n\
         \x20 {semantic_fingerprint},\n\
         \x20 {binding_fingerprint},\n\
         \x20 {managed_scope},\n\
         \x20 {semantic_profile},\n\
         \x20 {{ 0u, 0u, 0u, 0u }}\n\
         }};\n\
         _Static_assert(sizeof({prefix}_schema_package_chunks_v1) <=\n\
             {macro_prefix}_HOSTED_OBJECT_BYTES_MIN,\n\
             \"generated package descriptor exceeds the C hosted-object minimum\");\n\n\
         type_bridge_status_t TYPE_BRIDGE_CALL {prefix}_schema_package_open(\n\
             type_bridge_schema_package_t **out_package,\n\
             type_bridge_diagnostics_t **out_diagnostics) {{\n\
           return type_bridge_schema_package_open_chunked_v1(\n\
               &{prefix}_schema_package_chunks_v1, out_package, out_diagnostics);\n\
         }}\n",
        macro_prefix = prefix.to_ascii_uppercase(),
        schema_authority = chunked_byte_view_initializer(
            &format!("{prefix}_schema_authority_json"),
            authority.canonical_envelope_json.len(),
        ),
        declared_schema = chunked_byte_view_initializer(
            &format!("{prefix}_declared_schema_json"),
            authority.declared_schema_json.len(),
        ),
        runtime_projection = chunked_byte_view_initializer(
            &format!("{prefix}_runtime_projection_json"),
            projection_json.len(),
        ),
        semantic_fingerprint = chunked_byte_view_initializer(
            &format!("{prefix}_semantic_fingerprint_json"),
            semantic_json.len(),
        ),
        binding_fingerprint = chunked_byte_view_initializer(
            &format!("{prefix}_binding_fingerprint_json"),
            binding_json.len(),
        ),
        managed_scope = chunked_byte_view_initializer(
            &format!("{prefix}_managed_scope"),
            authority.managed_scope_id.len(),
        ),
        semantic_profile = chunked_byte_view_initializer(
            &format!("{prefix}_semantic_profile"),
            authority.semantic_profile_id.len(),
        ),
    );
    if ordered {
        let [add_alias_input, alias_preflight] = generated_alias_helper_symbols(prefix)?;
        let _ = write!(
            output,
            "\n\
             type_bridge_status_t TYPE_BRIDGE_CALL {prefix}_schema_package_open_v2(\n\
                 type_bridge_schema_package_t **out_package,\n\
                 type_bridge_execution_diagnostics_t **out_diagnostics) {{\n\
               return type_bridge_schema_package_open_chunked_v2(\n\
                   &{prefix}_schema_package_chunks_v1, out_package, out_diagnostics);\n\
             }}\n"
        );
        let _ = write!(
            output,
            "\n\
             type_bridge_status_t TYPE_BRIDGE_CALL {prefix}_migration_catalog_open(\n\
                 type_bridge_byte_view_t history_bundle,\n\
                 type_bridge_migration_catalog_t **out_catalog,\n\
                 type_bridge_diagnostics_t **out_diagnostics) {{\n\
               type_bridge_generated_opaque_input_v1_t alias_inputs[1];\n\
               size_t alias_input_count = 0u;\n\
               type_bridge_schema_package_t *package = NULL;\n\
               type_bridge_status_t status;\n\
               if (out_catalog == NULL || out_diagnostics == NULL) {{\n\
                 return TYPE_BRIDGE_STATUS_INVALID_ARGUMENT;\n\
               }}\n\
               {add_alias_input}(alias_inputs, &alias_input_count,\n\
                   TYPE_BRIDGE_GENERATED_INPUT_BYTES, history_bundle.data,\n\
                   history_bundle.length);\n\
               status = {alias_preflight}(alias_inputs, alias_input_count,\n\
                   out_catalog, sizeof(*out_catalog),\n\
                   out_diagnostics, sizeof(*out_diagnostics));\n\
               if (status != TYPE_BRIDGE_STATUS_OK) {{ return status; }}\n\
               *out_catalog = NULL;\n\
               *out_diagnostics = NULL;\n\
               status = {prefix}_schema_package_open(\n\
                   &package, out_diagnostics);\n\
               if (status != TYPE_BRIDGE_STATUS_OK) {{\n\
                 return status;\n\
               }}\n\
               status = type_bridge_migration_catalog_open(\n\
                   package, history_bundle, out_catalog, out_diagnostics);\n\
               type_bridge_status_t close_status =\n\
                   type_bridge_schema_package_close(&package);\n\
               return status == TYPE_BRIDGE_STATUS_OK ? close_status : status;\n\
             }}\n"
        );
    }
    Ok(output)
}

fn projected_token_kinds(ordered: bool) -> Vec<(ProjectedTokenKind, &'static str)> {
    let mut kinds = vec![
        (ProjectedTokenKind::Model, "model"),
        (ProjectedTokenKind::Field, "field"),
        (ProjectedTokenKind::Role, "role"),
        (ProjectedTokenKind::Function, "function"),
    ];
    if ordered {
        kinds.extend([
            (ProjectedTokenKind::Struct, "struct"),
            (ProjectedTokenKind::Attribute, "attribute"),
        ]);
    }
    kinds
}

fn generated_alias_helper_symbols(prefix: &str) -> Result<[String; 2], Diagnostic> {
    Ok([
        generated_symbol(prefix, "generated_alias_input_v1")?,
        generated_symbol(prefix, "generated_alias_preflight_v1")?,
    ])
}

fn render_generated_helpers(output: &mut String, prefix: &str) -> Result<(), Diagnostic> {
    let [add_input, preflight] = generated_alias_helper_symbols(prefix)?;
    let _ = write!(
        output,
        "static inline void {add_input}(\n\
           type_bridge_generated_opaque_input_v1_t *inputs,\n\
           size_t *input_count,\n\
           type_bridge_generated_opaque_input_kind_t kind,\n\
           const void *pointer, size_t count) {{\n\
           type_bridge_generated_opaque_input_v1_t *input;\n\
           if (pointer == NULL || count == 0u) {{ return; }}\n\
           input = &inputs[*input_count];\n\
           input->struct_size = sizeof(type_bridge_generated_opaque_input_v1_t);\n\
           input->version = TYPE_BRIDGE_GENERATED_ALIAS_PREFLIGHT_VERSION;\n\
           input->kind = kind;\n\
           input->reserved0 = 0u;\n\
           input->pointer = pointer;\n\
           input->count = count;\n\
           input->reserved[0] = 0u;\n\
           input->reserved[1] = 0u;\n\
           input->reserved[2] = 0u;\n\
           input->reserved[3] = 0u;\n\
           ++*input_count;\n\
         }}\n\n\
         static inline type_bridge_status_t {preflight}(\n\
           const type_bridge_generated_opaque_input_v1_t *inputs,\n\
           size_t input_count,\n\
           void *first_output, size_t first_output_length,\n\
           void *second_output, size_t second_output_length) {{\n\
           type_bridge_generated_output_range_v1_t outputs[2];\n\
           size_t output_count = 0u;\n\
           if (first_output != NULL) {{\n\
             outputs[output_count].struct_size = sizeof(type_bridge_generated_output_range_v1_t);\n\
             outputs[output_count].version = TYPE_BRIDGE_GENERATED_ALIAS_PREFLIGHT_VERSION;\n\
             outputs[output_count].pointer = first_output;\n\
             outputs[output_count].length = first_output_length;\n\
             outputs[output_count].reserved[0] = 0u;\n\
             outputs[output_count].reserved[1] = 0u;\n\
             outputs[output_count].reserved[2] = 0u;\n\
             outputs[output_count].reserved[3] = 0u;\n\
             ++output_count;\n\
           }}\n\
           if (second_output != NULL) {{\n\
             outputs[output_count].struct_size = sizeof(type_bridge_generated_output_range_v1_t);\n\
             outputs[output_count].version = TYPE_BRIDGE_GENERATED_ALIAS_PREFLIGHT_VERSION;\n\
             outputs[output_count].pointer = second_output;\n\
             outputs[output_count].length = second_output_length;\n\
             outputs[output_count].reserved[0] = 0u;\n\
             outputs[output_count].reserved[1] = 0u;\n\
             outputs[output_count].reserved[2] = 0u;\n\
             outputs[output_count].reserved[3] = 0u;\n\
             ++output_count;\n\
           }}\n\
           if (output_count == 0u) {{ return TYPE_BRIDGE_STATUS_INVALID_ARGUMENT; }}\n\
           return type_bridge_generated_opaque_alias_preflight_v1(\n\
               input_count == 0u ? NULL : inputs, input_count,\n\
               outputs, output_count);\n\
         }}\n\n"
    );
    Ok(())
}

fn projected_tokens(
    projection: &RuntimeProjection,
    ordered: bool,
) -> Vec<(ProjectedTokenKind, &'static str, u32)> {
    let mut tokens = Vec::new();
    for (kind, kind_name) in projected_token_kinds(ordered) {
        let mut ordinal = 0_u32;
        while projection.projected_token_identity(kind, ordinal).is_some() {
            tokens.push((kind, kind_name, ordinal));
            ordinal = ordinal
                .checked_add(1)
                .expect("projected token count is bounded below u32::MAX");
        }
    }
    tokens
}

fn projected_token_symbol(prefix: &str, kind_name: &str, ordinal: u32) -> String {
    format!("{prefix}_projected_{kind_name}_token_{ordinal}")
}

fn render_projected_token_declarations(
    output: &mut String,
    projection: &RuntimeProjection,
    prefix: &str,
    ordered: bool,
) {
    if !projection.models().is_empty() {
        output.push_str(
            "\n/* Generated-only schema tokens. Pass their addresses only through generated APIs. */\n",
        );
    }
    for (_, kind_name, ordinal) in projected_tokens(projection, ordered) {
        let symbol = projected_token_symbol(prefix, kind_name, ordinal);
        let _ = writeln!(
            output,
            "extern const type_bridge_projected_token_v1_t {symbol};"
        );
    }
}

fn render_projected_token_definitions(
    output: &mut String,
    projection: &RuntimeProjection,
    prefix: &str,
    ordered: bool,
) {
    let digest = projection
        .projection_fingerprint()
        .as_fingerprint()
        .digest()
        .bytes();
    for (kind, kind_name, ordinal) in projected_tokens(projection, ordered) {
        let symbol = projected_token_symbol(prefix, kind_name, ordinal);
        let _ = writeln!(
            output,
            "const type_bridge_projected_token_v1_t {symbol} = {{"
        );
        let _ = writeln!(
            output,
            "  sizeof(type_bridge_projected_token_v1_t),\n  {TYPE_BRIDGE_PROJECTED_TOKEN_VERSION}u,\n  {}u,\n  {ordinal}u,",
            kind.as_u32()
        );
        output.push_str("  { ");
        for byte in digest {
            let _ = write!(output, "0x{byte:02x}u, ");
        }
        output.push_str("},\n  { 0u, 0u, 0u, 0u }\n};\n\n");
    }
}

