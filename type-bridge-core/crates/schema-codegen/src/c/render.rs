fn canonical_codec_symbols(projection: &RuntimeProjection) -> Result<BTreeSet<String>, Diagnostic> {
    fn add_pair(symbols: &mut BTreeSet<String>, target: &str) -> Result<(), Diagnostic> {
        symbols.insert(generated_symbol(target, "canonical_encode")?);
        symbols.insert(generated_symbol(target, "canonical_decode")?);
        Ok(())
    }

    let mut symbols = BTreeSet::new();
    for model in projection.models().values() {
        match model.id().kind() {
            TypeKind::Attribute => add_pair(&mut symbols, model.target_name().as_str())?,
            TypeKind::Entity | TypeKind::Relation => {
                if let Some(target) = model.create().target_name() {
                    add_pair(&mut symbols, target.as_str())?;
                }
                if let Some(target) = model.reference_read().target_name() {
                    add_pair(&mut symbols, target.as_str())?;
                }
                add_pair(&mut symbols, model.target_name().as_str())?;
            }
            TypeKind::Struct => unreachable!("structs have their own projection map"),
        }
    }
    for structure in projection.structs().values() {
        add_pair(&mut symbols, structure.target_name().as_str())?;
        symbols.insert(generated_symbol(
            structure.target_name().as_str(),
            "canonical_close",
        )?);
        for field in structure.fields() {
            symbols.insert(generated_symbol(
                structure.target_name().as_str(),
                &format!("{}_member", field.target_name().as_str()),
            )?);
        }
    }
    Ok(symbols)
}

fn render_canonical_codec_declarations(
    output: &mut String,
    projection: &RuntimeProjection,
) -> Result<(), Diagnostic> {
    for model in projection.models().values() {
        match model.id().kind() {
            TypeKind::Attribute => {
                render_codec_declaration_pair(output, model.target_name().as_str())?;
            }
            TypeKind::Entity | TypeKind::Relation => {
                if let Some(target) = model.create().target_name() {
                    render_codec_declaration_pair(output, target.as_str())?;
                }
                if let Some(target) = model.reference_read().target_name() {
                    render_codec_declaration_pair(output, target.as_str())?;
                }
                render_codec_declaration_pair(output, model.target_name().as_str())?;
            }
            TypeKind::Struct => unreachable!("structs have their own projection map"),
        }
    }
    for structure in projection.structs().values() {
        render_codec_declaration_pair(output, structure.target_name().as_str())?;
        let close = generated_symbol(structure.target_name().as_str(), "canonical_close")?;
        let _ = writeln!(
            output,
            "type_bridge_status_t TYPE_BRIDGE_CALL {close}({} **value);",
            structure.target_name().as_str(),
        );
        for field in structure.fields() {
            let member = generated_symbol(
                structure.target_name().as_str(),
                &format!("{}_member", field.target_name().as_str()),
            )?;
            let _ = writeln!(
                output,
                "type_bridge_status_t TYPE_BRIDGE_CALL {member}(\n  const {} *value,\n  type_bridge_projected_struct_member_t **out_member,\n  type_bridge_execution_diagnostics_t **out_diagnostics);",
                structure.target_name().as_str(),
            );
        }
    }
    Ok(())
}

