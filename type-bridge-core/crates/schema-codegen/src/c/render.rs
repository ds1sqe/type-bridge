fn entity_crud_symbols(model: &ModelProjection) -> Result<Vec<String>, Diagnostic> {
    if model.create().target_name().is_none() {
        return Ok(Vec::new());
    }
    let mut symbols = Vec::new();
    for scope in ["database", "read_transaction", "write_transaction"] {
        if scope != "read_transaction" && model.create().target_name().is_some() {
            for operation in ["insert", "put"] {
                symbols.push(entity_crud_symbol(model, &format!("{scope}_{operation}"))?);
            }
        }
        symbols.push(entity_crud_symbol(model, &format!("{scope}_get_by_iid"))?);
        if scope != "read_transaction" && model.create().target_name().is_some() {
            symbols.push(entity_crud_symbol(model, &format!("{scope}_update"))?);
        }
        if scope != "read_transaction" {
            symbols.push(entity_crud_symbol(
                model,
                &format!("{scope}_delete_by_iid"),
            )?);
        }
        symbols.push(entity_crud_symbol(model, &format!("{scope}_count"))?);
    }
    Ok(symbols)
}

