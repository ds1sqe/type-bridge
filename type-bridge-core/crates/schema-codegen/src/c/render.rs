fn successor_crud_symbols(model: &ModelProjection) -> Result<Vec<String>, Diagnostic> {
    if model.create().target_name().is_none() {
        return Ok(Vec::new());
    }
    let mut symbols = Vec::new();
    for scope in ["database", "read_transaction", "write_transaction"] {
        if scope != "read_transaction" {
            symbols.push(entity_crud_symbol(model, &format!("{scope}_insert_v2"))?);
            if model_has_reference_key(model) {
                symbols.push(entity_crud_symbol(model, &format!("{scope}_put_v2"))?);
            }
        }
        symbols.push(entity_crud_symbol(
            model,
            &format!("{scope}_get_by_iid_v2"),
        )?);
        if scope != "read_transaction" {
            symbols.push(entity_crud_symbol(model, &format!("{scope}_update_v2"))?);
            symbols.push(entity_crud_symbol(
                model,
                &format!("{scope}_delete_by_iid_v2"),
            )?);
        }
        symbols.push(entity_crud_symbol(model, &format!("{scope}_count_v2"))?);
    }
    Ok(symbols)
}

fn successor_batch_function_names(
    model: &ModelProjection,
    operation: SuccessorBatchOperation,
) -> Result<Vec<String>, Diagnostic> {
    let target = model.target_name().as_str();
    let operation_name = operation.name;
    let mut symbols = vec![
        generated_symbol(target, &format!("{operation_name}_batch_builder_open"))?,
        generated_symbol(target, &format!("{operation_name}_batch_builder_add"))?,
        generated_symbol(target, &format!("{operation_name}_batch_builder_finish"))?,
        generated_symbol(target, &format!("{operation_name}_batch_builder_close"))?,
        generated_symbol(target, &format!("{operation_name}_batch_close"))?,
        generated_symbol(target, &format!("database_{operation_name}_batch_execute"))?,
        generated_symbol(
            target,
            &format!("write_transaction_{operation_name}_batch_execute"),
        )?,
        generated_symbol(target, &format!("{operation_name}_batch_result_count"))?,
    ];
    if operation.has_thing_result {
        symbols.push(generated_symbol(
            target,
            &format!("{operation_name}_batch_result_thing_at"),
        )?);
    }
    symbols.push(generated_symbol(
        target,
        &format!("{operation_name}_batch_result_close"),
    )?);
    Ok(symbols)
}

fn render_successor_model_api(
    output: &mut String,
    projection: &RuntimeProjection,
    prefix: &str,
) -> Result<(), Diagnostic> {
    output.push_str("\n/* Policy-aware nominal data operations. */\n");
    for model in projection.models().values().filter(|model| {
        matches!(model.id().kind(), TypeKind::Entity | TypeKind::Relation)
            && model.create().target_name().is_some()
    }) {
        let kind = match model.id().kind() {
            TypeKind::Entity => "entity",
            TypeKind::Relation => "relation",
            _ => unreachable!(),
        };
        render_successor_model_crud(output, projection, model, prefix, kind)?;
        for operation in successor_batch_operations(model) {
            render_successor_model_batch(output, projection, model, prefix, operation)?;
        }
    }
    Ok(())
}

