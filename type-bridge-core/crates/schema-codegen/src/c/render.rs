fn render_canonical_codec_definitions(
    output: &mut String,
    projection: &RuntimeProjection,
    prefix: &str,
) -> Result<(), Diagnostic> {
    for model in projection.models().values() {
        match model.id().kind() {
            TypeKind::Attribute => {
                let attribute =
                    type_bridge_contract::id::AttributeId::new(model.id().label().as_str())?;
                let token = attribute_token_symbol(projection, prefix, &attribute)?;
                render_codec_definition_pair(
                    output,
                    model.target_name().as_str(),
                    "type_bridge_projected_value_t",
                    "type_bridge_canonical_record_encode_attribute_v1",
                    "type_bridge_canonical_record_decode_attribute_v1",
                    &token,
                )?;
            }
            TypeKind::Entity | TypeKind::Relation => {
                let token = model_token_symbol(projection, prefix, model.id())?;
                if let Some(target) = model.create().target_name() {
                    render_codec_definition_pair(
                        output,
                        target.as_str(),
                        "type_bridge_projected_create_t",
                        "type_bridge_canonical_record_encode_create_v1",
                        "type_bridge_canonical_record_decode_create_v1",
                        &token,
                    )?;
                }
                if let Some(target) = model.reference_read().target_name() {
                    render_codec_definition_pair(
                        output,
                        target.as_str(),
                        "type_bridge_projected_reference_t",
                        "type_bridge_canonical_record_encode_reference_v1",
                        "type_bridge_canonical_record_decode_reference_v1",
                        &token,
                    )?;
                }
                render_codec_definition_pair(
                    output,
                    model.target_name().as_str(),
                    "type_bridge_projected_thing_t",
                    "type_bridge_canonical_record_encode_snapshot_v1",
                    "type_bridge_canonical_record_decode_snapshot_v1",
                    &token,
                )?;
            }
            TypeKind::Struct => unreachable!("structs have their own projection map"),
        }
    }
    for structure in projection.structs().values() {
        let token = struct_token_symbol(projection, prefix, structure.id())?;
        let target = structure.target_name().as_str();
        render_codec_definition_pair(
            output,
            target,
            "type_bridge_projected_struct_t",
            "type_bridge_canonical_record_encode_struct_v1",
            "type_bridge_canonical_record_decode_struct_v1",
            &token,
        )?;
        let close = generated_symbol(target, "canonical_close")?;
        let _ = write!(
            output,
            "type_bridge_status_t TYPE_BRIDGE_CALL {close}({target} **value) {{\n\
               type_bridge_projected_struct_t *generic_value;\n\
               type_bridge_status_t status;\n\
               if (value == NULL) {{ return TYPE_BRIDGE_STATUS_INVALID_ARGUMENT; }}\n\
               generic_value = (type_bridge_projected_struct_t *)*value;\n\
               status = type_bridge_projected_struct_close(&generic_value);\n\
               *value = ({target} *)generic_value;\n\
               return status;\n\
             }}\n\n",
        );
        for (index, field) in structure.fields().iter().enumerate() {
            let member =
                generated_symbol(target, &format!("{}_member", field.target_name().as_str()))?;
            let _ = write!(
                output,
                "type_bridge_status_t TYPE_BRIDGE_CALL {member}(\n\
                   const {target} *value,\n\
                   type_bridge_projected_struct_member_t **out_member,\n\
                   type_bridge_execution_diagnostics_t **out_diagnostics) {{\n\
                   return type_bridge_projected_struct_member_at_v1(\n\
                       (const type_bridge_projected_struct_t *)value, &{token}, {index}u,\n\
                       out_member, out_diagnostics);\n\
                 }}\n\n",
            );
        }
    }
    Ok(())
}

