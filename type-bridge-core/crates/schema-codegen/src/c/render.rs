fn role_union_symbols<'a>(
    projection: &'a RuntimeProjection,
    role: &'a RoleTokenProjection,
    prefix: &str,
) -> Result<RoleUnionSymbols<'a>, Diagnostic> {
    let target = role
        .player_union_target_name()
        .ok_or_else(|| {
            invalid(
                "c_emitter_role_union_missing",
                "projected C relation role has no nominal player-union name",
            )
        })?
        .as_str();
    let mut variants = Vec::with_capacity(role.accepted_players().len());
    for player in role.accepted_players() {
        let model = projection.models().get(player).ok_or_else(|| {
            invalid(
                "c_emitter_role_player_missing",
                "projected C relation role references an absent player model",
            )
        })?;
        if !matches!(player.kind(), TypeKind::Entity | TypeKind::Relation)
            || model.reference_read().target_name().is_none()
        {
            return Err(invalid(
                "c_emitter_role_player_reference_missing",
                "projected C role players must expose nominal reference models",
            ));
        }
        let member = projected_member_suffix(prefix, model.target_name())?;
        variants.push(RoleUnionVariantSymbols {
            model,
            model_token: model_token_symbol(projection, prefix, player)?,
            model_ordinal: model_token_ordinal(projection, player)?,
            kind_constant: generated_symbol(target, &format!("kind_{member}"))?,
            from_reference: generated_symbol(target, &format!("from_{member}"))?,
            as_reference: generated_symbol(target, &format!("as_{member}"))?,
        });
    }
    Ok(RoleUnionSymbols {
        target,
        role_token: role_token_symbol(projection, prefix, role.owner(), role.role())?,
        kind_type: generated_symbol(target, "kind_t")?,
        kind_unknown: generated_symbol(target, "kind_unknown")?,
        kind_function: generated_symbol(target, "kind")?,
        close: generated_symbol(target, "close")?,
        variants,
    })
}

fn render_role_union_declarations(
    output: &mut String,
    projection: &RuntimeProjection,
    prefix: &str,
) -> Result<(), Diagnostic> {
    for model in projection
        .models()
        .values()
        .filter(|model| model.id().kind() == TypeKind::Relation)
    {
        for role in model.query_tokens().roles().values() {
            let symbols = role_union_symbols(projection, role, prefix)?;
            let _ = writeln!(
                output,
                "\n/* Closed owned role-player union `{}`. */",
                symbols.target
            );
            let _ = writeln!(output, "typedef uint32_t {};", symbols.kind_type);
            let _ = writeln!(output, "#define {} UINT32_C(0)", symbols.kind_unknown);
            for (index, variant) in symbols.variants.iter().enumerate() {
                let _ = writeln!(
                    output,
                    "#define {} UINT32_C({})",
                    variant.kind_constant,
                    index + 1
                );
            }
            for variant in &symbols.variants {
                let reference = variant
                    .model
                    .reference_read()
                    .target_name()
                    .expect("role-player reference target was validated");
                let _ = write!(
                    output,
                    "type_bridge_status_t TYPE_BRIDGE_CALL {}(\n\
                       const {} *reference,\n\
                       {} **out_player,\n\
                       type_bridge_execution_diagnostics_t **out_diagnostics);\n\
                     type_bridge_status_t TYPE_BRIDGE_CALL {}(\n\
                       const {} *player,\n\
                       {} **out_reference,\n\
                       type_bridge_execution_diagnostics_t **out_diagnostics);\n",
                    variant.from_reference,
                    reference.as_str(),
                    symbols.target,
                    variant.as_reference,
                    symbols.target,
                    reference.as_str(),
                );
            }
            let _ = write!(
                output,
                "type_bridge_status_t TYPE_BRIDGE_CALL {}(\n\
                   const {} *player, {} *out_kind,\n\
                   type_bridge_execution_diagnostics_t **out_diagnostics);\n\
                 type_bridge_status_t TYPE_BRIDGE_CALL {}({} **player);\n",
                symbols.kind_function,
                symbols.target,
                symbols.kind_type,
                symbols.close,
                symbols.target,
            );
        }
    }
    Ok(())
}

