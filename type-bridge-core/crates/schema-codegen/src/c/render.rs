fn bounded_generated_identifier(unbounded: &str) -> Result<String, Diagnostic> {
    if TargetIdentifier::c(unbounded).is_ok() {
        return Ok(unbounded.to_owned());
    }
    let digest = Fingerprint::compute(
        FingerprintDomain::new(C_GENERATED_SYMBOL_DOMAIN)?,
        CanonicalizationVersion::new(C_GENERATED_SYMBOL_CANONICALIZATION)?,
        None,
        unbounded.as_bytes(),
    )
    .digest()
    .to_hex();
    let mut stem_bytes = C_MAX_TARGET_IDENTIFIER_BYTES - digest.len() - 1;
    while unbounded.as_bytes().get(stem_bytes - 1) == Some(&b'_') {
        stem_bytes -= 1;
    }
    let bounded = format!("{}_{}", &unbounded[..stem_bytes], digest);
    TargetIdentifier::c(bounded.clone())?;
    Ok(bounded)
}

fn generated_symbol(base: &str, suffix: &str) -> Result<String, Diagnostic> {
    bounded_generated_identifier(&format!("{base}_{suffix}"))
}

pub(super) fn bound_long_generated_identifiers(source: &str) -> Result<String, Diagnostic> {
    let mut output = String::with_capacity(source.len());
    let mut start = 0;
    let bytes = source.as_bytes();
    while start < bytes.len() {
        let byte = bytes[start];
        if byte.is_ascii_alphabetic() || byte == b'_' {
            let mut end = start + 1;
            while end < bytes.len() && (bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_') {
                end += 1;
            }
            let identifier = &source[start..end];
            if identifier.len() > C_MAX_TARGET_IDENTIFIER_BYTES {
                output.push_str(&bounded_generated_identifier(identifier)?);
            } else {
                output.push_str(identifier);
            }
            start = end;
        } else {
            output.push(byte as char);
            start += 1;
        }
    }
    Ok(output)
}

