    #[test]
    fn colliding_symbols_alias_the_older_version() {
        // `person` exists in both snapshots and is referenced on both sides:
        // the newer version keeps the bare name, the older one is aliased.
        let base = schema_with(
            vec![entity("person", vec![owned_optional("age")])],
            vec!["age"],
        );
        let target = schema_with(vec![entity("person", vec![])], vec!["age", "nickname"]);
        let operations = vec![
            OperationSpec::AddOwnership {
                owner_type: "person".to_string(),
                attribute: owned_optional("nickname"),
            },
            OperationSpec::RemoveOwnership {
                owner_type: "person".to_string(),
                attr_name: "age".to_string(),
            },
        ];

        let rendered = render_migration_python(&PythonRenderRequest {
            operations: &operations,
            app_label: "migrations",
            name: "swap_ownership",
            dependencies: &[],
            generated_at: "t",
            pre_version: Some("v0001"),
            post_version: "v0002",
            base: &base,
            target: &target,
            declared_intent: None,
        })
        .expect("render should succeed");

        assert!(
            rendered.contains("from migrations.snapshots.v0001 import Age, Person as PersonV0001"),
            "older version must alias the colliding symbol: {rendered}"
        );
        assert!(rendered.contains("ops.RemoveOwnership(PersonV0001, Age),"));
        assert!(!rendered.contains("ops.AddOwnership(person"));
    }

