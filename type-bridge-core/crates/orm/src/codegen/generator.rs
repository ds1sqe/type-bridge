// ---------------------------------------------------------------------------
// Topological sort
// ---------------------------------------------------------------------------

fn topological_sort<T, F>(map: &BTreeMap<String, T>, get_parent: F) -> Vec<String>
where
    F: Fn(&T) -> Option<&str>,
{
    let mut result = Vec::new();
    let mut visited = HashSet::new();

    fn visit<T2, F2>(
        name: &str,
        map: &BTreeMap<String, T2>,
        get_parent: &F2,
        visited: &mut HashSet<String>,
        result: &mut Vec<String>,
    ) where
        F2: Fn(&T2) -> Option<&str>,
    {
        if visited.contains(name) {
            return;
        }
        visited.insert(name.to_string());
        if let Some(entry) = map.get(name)
            && let Some(parent) = get_parent(entry)
        {
            visit(parent, map, get_parent, visited, result);
        }
        result.push(name.to_string());
    }

    for name in map.keys() {
        visit(name, map, &get_parent, &mut visited, &mut result);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    fn basic_schema_tql() -> &'static str {
        "define\nattribute name, value string;\nattribute age, value long;\nentity person, owns name @key, owns age, plays employment:employee;"
    }

    fn inheritance_schema_tql() -> &'static str {
        "define\nattribute name, value string;\nattribute breed, value string;\nentity animal @abstract, owns name @key;\nentity dog sub animal, owns breed, plays ownership:pet;"
    }

    fn relation_schema_tql() -> &'static str {
        "define\nattribute name, value string;\nattribute position, value string;\nentity person, owns name @key, plays employment:employee;\nentity company, owns name @key, plays employment:employer;\nrelation employment, relates employee, relates employer, owns position;"
    }

    #[test]
    fn generate_basic_attributes() {
        let models = generate_from_typeql(basic_schema_tql()).unwrap();
        assert!(models.attributes_rs.contains("define_attribute!(Age, \"age\", \"long\");"));
        assert!(models.attributes_rs.contains("define_attribute!(Name, \"name\", \"string\");"));
    }

    #[test]
    fn generate_basic_entity() {
        let models = generate_from_typeql(basic_schema_tql()).unwrap();
        assert!(
            models.entities_rs.contains("#[entity(name = \"person\")]"),
            "entity attr missing: {}",
            models.entities_rs
        );
        assert!(
            models.entities_rs.contains("pub struct Person"),
            "struct missing: {}",
            models.entities_rs
        );
        assert!(
            models.entities_rs.contains("#[field(key)]"),
            "key annotation missing: {}",
            models.entities_rs
        );
    }

    #[test]
    fn generate_abstract_and_inheritance() {
        let models = generate_from_typeql(inheritance_schema_tql()).unwrap();

        // Animal should be abstract
        assert!(
            models.entities_rs.contains("r#abstract"),
            "abstract missing: {}",
            models.entities_rs
        );
        // Dog should extend animal
        assert!(
            models.entities_rs.contains("extends = \"animal\""),
            "extends missing: {}",
            models.entities_rs
        );
        // Animal should appear before Dog (topological order)
        let animal_pos = models.entities_rs.find("struct Animal").unwrap();
        let dog_pos = models.entities_rs.find("struct Dog").unwrap();
        assert!(
            animal_pos < dog_pos,
            "Animal should come before Dog: {}",
            models.entities_rs
        );
    }

    #[test]
    fn generate_relation_with_roles() {
        let models = generate_from_typeql(relation_schema_tql()).unwrap();

        assert!(
            models.relations_rs.contains("#[relation(name = \"employment\")]"),
            "relation attr missing: {}",
            models.relations_rs
        );
        assert!(
            models.relations_rs.contains("pub struct Employment"),
            "struct missing: {}",
            models.relations_rs
        );
        // Role player resolution
        assert!(
            models.relations_rs.contains("player_type = \"person\""),
            "employee role missing: {}",
            models.relations_rs
        );
        assert!(
            models.relations_rs.contains("player_type = \"company\""),
            "employer role missing: {}",
            models.relations_rs
        );
    }

    #[test]
    fn generate_mod_rs_has_re_exports() {
        let models = generate_from_typeql(basic_schema_tql()).unwrap();
        assert!(models.mod_rs.contains("pub mod attributes;"));
        assert!(models.mod_rs.contains("pub mod entities;"));
        assert!(models.mod_rs.contains("pub mod relations;"));
    }

    #[test]
    fn generate_optional_field() {
        let tql = "define\nattribute name, value string;\nattribute nickname, value string;\nentity person, owns name @key, owns nickname @card(0..1);";
        let models = generate_from_typeql(tql).unwrap();
        assert!(
            models.entities_rs.contains("Option<Nickname>"),
            "optional field missing: {}",
            models.entities_rs
        );
    }

    #[test]
    fn generate_multi_value_field() {
        let tql = "define\nattribute name, value string;\nattribute tag, value string;\nentity person, owns name @key, owns tag @card(0..);";
        let models = generate_from_typeql(tql).unwrap();
        assert!(
            models.entities_rs.contains("Vec<Tag>"),
            "multi-value field missing: {}",
            models.entities_rs
        );
    }

    #[test]
    fn generate_skips_abstract_attributes() {
        let tql = "define\nattribute content @abstract, value string;\nattribute name sub content, value string;\nentity person, owns name @key;";
        let models = generate_from_typeql(tql).unwrap();
        // Abstract attribute should not generate define_attribute!
        assert!(
            !models.attributes_rs.contains("define_attribute!(Content"),
            "abstract attr should be skipped: {}",
            models.attributes_rs
        );
        // Concrete child should still be generated
        assert!(
            models.attributes_rs.contains("define_attribute!(Name"),
            "concrete attr should be generated: {}",
            models.attributes_rs
        );
    }

    #[test]
    fn duplicate_role_names_get_suffixed() {
        let tql = "define\nattribute name, value string;\nentity person, owns name @key, plays friendship:friend;\nrelation friendship, relates friend;";
        let models = generate_from_typeql(tql).unwrap();
        assert!(
            models.relations_rs.contains("pub struct Friendship"),
            "struct missing: {}",
            models.relations_rs
        );
    }
}
