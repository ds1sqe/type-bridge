//! Code generator: TypeQL schema → Rust source files.
//!
//! Parses a TypeQL `define` block using `type_bridge_core_lib::TypeSchema`
//! and generates Rust source files with derive macros.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write;

use type_bridge_core_lib::schema::{Cardinality, EntityType, OwnedAttribute, RelationType, TypeSchema};

use super::naming::{to_pascal_case, to_snake_case};

/// Generated Rust model source files.
#[derive(Debug, Clone)]
pub struct GeneratedModels {
    /// `mod.rs` with re-exports.
    pub mod_rs: String,
    /// `attributes.rs` with `define_attribute!` invocations.
    pub attributes_rs: String,
    /// `entities.rs` with entity struct definitions.
    pub entities_rs: String,
    /// `relations.rs` with relation struct definitions.
    pub relations_rs: String,
}

/// Parse TypeQL and generate Rust model source code.
pub fn generate_from_typeql(input: &str) -> Result<GeneratedModels, String> {
    let schema = TypeSchema::from_typeql(input).map_err(|e| e.to_string())?;
    Ok(generate_rust_models(&schema))
}

/// Generate Rust model source from a resolved `TypeSchema`.
pub fn generate_rust_models(schema: &TypeSchema) -> GeneratedModels {
    let attributes_rs = generate_attributes(schema);
    let entities_rs = generate_entities(schema);
    let relations_rs = generate_relations(schema);
    let mod_rs = generate_mod_rs();

    GeneratedModels {
        mod_rs,
        attributes_rs,
        entities_rs,
        relations_rs,
    }
}

/// Map TypeDB value type string to the Rust `define_attribute!` value type name.
fn value_type_to_rust(vt: &str) -> &str {
    match vt {
        "string" => "string",
        "long" => "long",
        "double" => "double",
        "boolean" => "boolean",
        "date" => "date",
        "datetime" => "datetime",
        "datetime-tz" => "datetime-tz",
        "decimal" => "decimal",
        "duration" => "duration",
        other => other,
    }
}

// ---------------------------------------------------------------------------
// Attributes
// ---------------------------------------------------------------------------

fn generate_attributes(schema: &TypeSchema) -> String {
    let mut out = String::new();
    writeln!(out, "//! Generated attribute types.").unwrap();
    writeln!(out, "//!").unwrap();
    writeln!(out, "//! Auto-generated by type-bridge codegen. Do not edit manually.").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use type_bridge_orm::define_attribute;").unwrap();
    writeln!(out).unwrap();

    for attr in schema.attributes.values() {
        // Skip abstract attribute types — they have no concrete value type
        if attr.is_abstract {
            continue;
        }
        let struct_name = to_pascal_case(&attr.name);
        let vt = value_type_to_rust(&attr.value_type);
        writeln!(
            out,
            "define_attribute!({}, \"{}\", \"{}\");",
            struct_name, attr.name, vt
        )
        .unwrap();
    }

    out
}

